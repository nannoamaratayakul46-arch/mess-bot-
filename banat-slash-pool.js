const usedBySender = new Map();
const lastByThread = new Map();
const HISTORY_LIMIT = 500;

function rememberBounded(map, key, value) {
  map.delete(key);
  map.set(key, value);
  while (map.size > HISTORY_LIMIT) map.delete(map.keys().next().value);
}

function pickSlashPoolInsult(threadId, senderId) {
  const thread = String(threadId || "global");
  const sender = String(senderId || "unknown");
  const key = thread + ":" + sender;
  const used = usedBySender.get(key) || new Set();
  let candidates = INSULTS.filter((line) => !used.has(line));
  if (!candidates.length) {
    used.clear();
    candidates = INSULTS.slice();
  }
  const last = lastByThread.get(thread);
  if (candidates.length > 1 && last) {
    const fresh = candidates.filter((line) => line !== last);
    if (fresh.length) candidates = fresh;
  }
  const selected = candidates[Math.floor(Math.random() * candidates.length)];
  used.add(selected);
  rememberBounded(usedBySender, key, used);
  rememberBounded(lastByThread, thread, selected);
  return selected;
}

function getSlashPoolToggleReply(enabled) {
  // Keep the command response conversational; don't expose an activation panel.
  return enabled
    ? "andito na bangungot niyo"
    : "wala na bangungot niyo";
}

module.exports = { INSULTS, pickSlashPoolInsult, getSlashPoolToggleReply };
